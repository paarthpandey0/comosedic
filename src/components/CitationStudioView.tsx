import { useMemo, useState } from 'react';
import {
  Check,
  Copy,
  Download,
  ExternalLink,
  Loader2,
  Quote,
  Search,
  Trash2,
} from 'lucide-react';
import type {
  AcademicMemory,
  CitationEntry,
  CitationSourceType,
  Subject,
} from '../types';
import {
  awardLearningXp,
  createCitationEntry,
  deleteCitationEntry,
} from '../services/studyDb';
import { generateAcademicCitation } from '../services/geminiApi';

interface CitationStudioViewProps {
  uid: string;
  academicMemory: AcademicMemory | null;
  subjects: Subject[];
  citations: CitationEntry[];
}

type CitationFormatKey = 'apa' | 'mla' | 'chicago' | 'harvard' | 'ieee' | 'bibtex';

const FORMAT_LABELS: Array<{ id: CitationFormatKey; label: string }> = [
  { id: 'apa', label: 'APA 7' },
  { id: 'mla', label: 'MLA 9' },
  { id: 'chicago', label: 'Chicago' },
  { id: 'harvard', label: 'Harvard' },
  { id: 'ieee', label: 'IEEE' },
  { id: 'bibtex', label: 'BibTeX' },
];

const SOURCE_TYPES: Array<{ id: CitationSourceType; label: string }> = [
  { id: 'paper', label: 'Research Paper' },
  { id: 'article', label: 'Journal / News Article' },
  { id: 'book', label: 'Book / Textbook' },
  { id: 'website', label: 'Website / Documentation' },
  { id: 'video', label: 'Lecture / Video' },
];

export function CitationStudioView({
  uid,
  academicMemory,
  subjects,
  citations,
}: CitationStudioViewProps) {
  const [subjectId, setSubjectId] = useState(subjects[0]?.id || 'general');
  const [sourceType, setSourceType] = useState<CitationSourceType>('paper');
  const [queryInput, setQueryInput] = useState('');
  const [activeFormat, setActiveFormat] = useState<CitationFormatKey>('apa');
  const [filterSubjectId, setFilterSubjectId] = useState<string>('all');
  const [searchFilter, setSearchFilter] = useState('');

  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState('');
  const [notice, setNotice] = useState('');
  const [verificationNote, setVerificationNote] = useState('');
  const [copiedId, setCopiedId] = useState<string>('');

  const filteredCitations = useMemo(() => {
    const q = searchFilter.trim().toLowerCase();
    return citations.filter((c) => {
      if (filterSubjectId !== 'all' && c.subjectId !== filterSubjectId) return false;
      if (!q) return true;
      return (
        c.title.toLowerCase().includes(q) ||
        c.authors.toLowerCase().includes(q) ||
        c.year.toLowerCase().includes(q) ||
        c.annotation.toLowerCase().includes(q)
      );
    });
  }, [citations, filterSubjectId, searchFilter]);

  const handleGenerate = async () => {
    if (!queryInput.trim()) {
      setError('Enter a paper title, DOI, ISBN, URL, or author & topic to cite.');
      return;
    }

    setGenerating(true);
    setError('');
    setNotice('');
    setVerificationNote('');
    try {
      const subject = subjects.find((s) => s.id === subjectId);
      const res = await generateAcademicCitation({
        queryInput: queryInput.trim(),
        sourceType,
        subjectName: subject?.name || 'General Research',
      });

      await createCitationEntry(uid, {
        subjectId: subjectId || 'general',
        title: res.title,
        authors: res.authors,
        year: res.year,
        sourceType,
        url: res.url,
        inText: res.inText,
        apa: res.apa,
        mla: res.mla,
        chicago: res.chicago,
        harvard: res.harvard,
        ieee: res.ieee,
        bibtex: res.bibtex,
        annotation: res.annotation,
      });
      void awardLearningXp(uid, academicMemory, 15);
      setVerificationNote(res.verificationNote || '');
      setQueryInput('');
      setNotice(`Saved "${res.title}" across all 6 citation styles.`);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to generate citation.');
    } finally {
      setGenerating(false);
    }
  };

  const handleCopy = async (id: string, text: string) => {
    try {
      await navigator.clipboard.writeText(text);
      setCopiedId(id);
      setTimeout(() => setCopiedId((prev) => (prev === id ? '' : prev)), 1800);
    } catch {
      setError('Clipboard access was blocked by the browser.');
    }
  };

  const handleExportBibliography = (mode: 'txt' | 'bib') => {
    if (filteredCitations.length === 0) return;
    const formatTitle = FORMAT_LABELS.find((f) => f.id === activeFormat)?.label || 'APA 7';
    let content = '';
    let mime = 'text/plain;charset=utf-8';
    let filename = `bibliography-${activeFormat}.txt`;

    if (mode === 'bib') {
      content = filteredCitations.map((c) => c.bibtex.trim()).filter(Boolean).join('\n\n');
      filename = 'references.bib';
    } else {
      const header = `References (${formatTitle})\nGenerated by Lumina Study\n${'='.repeat(48)}\n\n`;
      const body = filteredCitations
        .map((c, idx) => {
          const formatted = c[activeFormat] || c.apa;
          return `${idx + 1}. ${formatted}${c.annotation ? `\n   Annotation: ${c.annotation}` : ''}`;
        })
        .join('\n\n');
      content = header + body;
    }

    const blob = new Blob([content], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-end justify-between gap-3">
        <div>
          <h1 className="font-display text-2xl font-bold text-slate-900 dark:text-white flex items-center gap-2.5">
            <Quote className="w-6 h-6 text-indigo-600 dark:text-indigo-400" />
            Citation &amp; Bibliography Studio
          </h1>
          <p className="text-sm text-slate-500 dark:text-slate-400 mt-1">
            Look up academic sources with live search grounding and format instant APA 7, MLA 9, Chicago, Harvard, IEEE, and BibTeX references.
          </p>
        </div>
        <div className="text-xs text-slate-500 dark:text-slate-400 tabular-nums">
          {citations.length} saved source{citations.length === 1 ? '' : 's'}
        </div>
      </div>

      {/* Generator Panel */}
      <div className="rounded-2xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-[#1A202C] p-5 space-y-4">
        <div className="grid grid-cols-1 md:grid-cols-12 gap-3">
          <select
            value={subjectId}
            onChange={(e) => setSubjectId(e.target.value)}
            className="md:col-span-3 px-3.5 py-2.5 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-900 text-sm text-slate-900 dark:text-white"
          >
            <option value="general">General Research</option>
            {subjects.map((s) => (
              <option key={s.id} value={s.id}>
                {s.name}
              </option>
            ))}
          </select>

          <select
            value={sourceType}
            onChange={(e) => setSourceType(e.target.value as CitationSourceType)}
            className="md:col-span-3 px-3.5 py-2.5 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-900 text-sm text-slate-900 dark:text-white"
          >
            {SOURCE_TYPES.map((t) => (
              <option key={t.id} value={t.id}>
                {t.label}
              </option>
            ))}
          </select>

          <input
            type="text"
            value={queryInput}
            onChange={(e) => setQueryInput(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === 'Enter' && !generating) void handleGenerate();
            }}
            placeholder="Paste DOI, URL, ISBN, or title + author (e.g., Attention Is All You Need Vaswani 2017)"
            className="md:col-span-6 px-3.5 py-2.5 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-900 text-sm text-slate-900 dark:text-white"
          />
        </div>

        <div className="flex flex-wrap items-center justify-between gap-3">
          <button
            type="button"
            onClick={() => void handleGenerate()}
            disabled={generating}
            className="inline-flex items-center gap-2 px-4 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-700 disabled:opacity-50 text-white text-sm font-medium whitespace-nowrap"
          >
            {generating ? <Loader2 className="w-4 h-4 animate-spin" /> : <Quote className="w-4 h-4" />}
            Lookup &amp; Format Citation
          </button>

          <div className="text-xs space-y-0.5">
            {error && <p className="text-rose-600 dark:text-rose-400">{error}</p>}
            {notice && <p className="text-emerald-700 dark:text-emerald-400">{notice}</p>}
            {verificationNote && (
              <p className="text-slate-500 dark:text-slate-400">
                Verification: {verificationNote}
              </p>
            )}
          </div>
        </div>
      </div>

      {/* Format Bar + Filter + Export */}
      <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-3">
        <div className="flex flex-wrap items-center gap-1.5">
          {FORMAT_LABELS.map((fmt) => {
            const active = activeFormat === fmt.id;
            return (
              <button
                key={fmt.id}
                type="button"
                onClick={() => setActiveFormat(fmt.id)}
                className={`px-3 py-1.5 rounded-lg text-xs font-medium transition-colors whitespace-nowrap ${
                  active
                    ? 'bg-slate-900 dark:bg-indigo-600 text-white'
                    : 'border border-slate-200 dark:border-slate-700 bg-white dark:bg-[#1A202C] text-slate-600 dark:text-slate-300 hover:bg-slate-50 dark:hover:bg-slate-800'
                }`}
              >
                {fmt.label}
              </button>
            );
          })}
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <div className="relative">
            <Search className="w-3.5 h-3.5 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
            <input
              type="text"
              value={searchFilter}
              onChange={(e) => setSearchFilter(e.target.value)}
              placeholder="Filter references..."
              className="pl-8 pr-3 py-1.5 rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-[#1A202C] text-xs text-slate-900 dark:text-white"
            />
          </div>

          <select
            value={filterSubjectId}
            onChange={(e) => setFilterSubjectId(e.target.value)}
            className="px-2.5 py-1.5 rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-[#1A202C] text-xs text-slate-700 dark:text-slate-200"
          >
            <option value="all">All Subjects</option>
            <option value="general">General Research</option>
            {subjects.map((s) => (
              <option key={s.id} value={s.id}>
                {s.name}
              </option>
            ))}
          </select>

          <button
            type="button"
            onClick={() => handleExportBibliography('txt')}
            disabled={filteredCitations.length === 0}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-[#1A202C] text-xs font-medium text-slate-700 dark:text-slate-200 hover:bg-slate-50 dark:hover:bg-slate-800 disabled:opacity-40 whitespace-nowrap"
          >
            <Download className="w-3.5 h-3.5" />
            Export .txt
          </button>

          <button
            type="button"
            onClick={() => handleExportBibliography('bib')}
            disabled={filteredCitations.length === 0}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-[#1A202C] text-xs font-medium text-slate-700 dark:text-slate-200 hover:bg-slate-50 dark:hover:bg-slate-800 disabled:opacity-40 whitespace-nowrap"
          >
            <Download className="w-3.5 h-3.5" />
            Export .bib
          </button>
        </div>
      </div>

      {/* Saved Bibliography List */}
      {filteredCitations.length === 0 ? (
        <div className="rounded-2xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-[#1A202C] p-12 text-center space-y-2">
          <p className="text-sm font-medium text-slate-700 dark:text-slate-200">
            No saved citations match this filter yet.
          </p>
          <p className="text-xs text-slate-500 dark:text-slate-400">
            Enter a paper title, DOI, ISBN, or webpage above to build your annotated bibliography.
          </p>
        </div>
      ) : (
        <div className="space-y-3">
          {filteredCitations.map((entry) => {
            const subjName = subjects.find((s) => s.id === entry.subjectId)?.name || 'General Research';
            const activeText = entry[activeFormat] || entry.apa;
            const isCopied = copiedId === `${entry.id}_${activeFormat}`;
            const isInTextCopied = copiedId === `${entry.id}_intext`;

            return (
              <div
                key={entry.id}
                className="rounded-2xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-[#1A202C] p-5 space-y-3"
              >
                <div className="flex items-start justify-between gap-4">
                  <div className="min-w-0">
                    <h2 className="font-display text-base font-bold text-slate-900 dark:text-white">
                      {entry.title}
                    </h2>
                    <p className="text-xs text-slate-500 dark:text-slate-400 mt-0.5 tabular-nums">
                      {entry.authors || 'Unknown Author'} · {entry.year || 'n.d.'} · {entry.sourceType} · {subjName}
                    </p>
                  </div>
                  <div className="flex items-center gap-1.5 shrink-0">
                    {entry.url && (
                      <a
                        href={entry.url}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="p-1.5 rounded-lg text-slate-400 hover:text-indigo-600 dark:hover:text-indigo-400 hover:bg-slate-100 dark:hover:bg-slate-800"
                        aria-label="Open original source"
                      >
                        <ExternalLink className="w-4 h-4" />
                      </a>
                    )}
                    <button
                      type="button"
                      onClick={() => void deleteCitationEntry(entry.id)}
                      className="p-1.5 rounded-lg text-slate-400 hover:text-rose-600 hover:bg-slate-100 dark:hover:bg-slate-800"
                      aria-label="Delete citation"
                    >
                      <Trash2 className="w-4 h-4" />
                    </button>
                  </div>
                </div>

                {/* Formatted Reference Box */}
                <div className="rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50/80 dark:bg-slate-900/60 p-3.5 flex flex-col sm:flex-row sm:items-start justify-between gap-3">
                  <pre
                    className={`text-sm text-slate-800 dark:text-slate-100 whitespace-pre-wrap break-words flex-1 ${
                      activeFormat === 'bibtex' ? 'font-mono text-xs' : 'font-sans leading-relaxed'
                    }`}
                  >
                    {activeText}
                  </pre>
                  <button
                    type="button"
                    onClick={() => void handleCopy(`${entry.id}_${activeFormat}`, activeText)}
                    className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-[#1A202C] text-xs font-medium text-slate-700 dark:text-slate-200 hover:bg-slate-100 dark:hover:bg-slate-800 shrink-0 whitespace-nowrap"
                  >
                    {isCopied ? (
                      <>
                        <Check className="w-3.5 h-3.5 text-emerald-600" />
                        Copied
                      </>
                    ) : (
                      <>
                        <Copy className="w-3.5 h-3.5" />
                        Copy {FORMAT_LABELS.find((f) => f.id === activeFormat)?.label}
                      </>
                    )}
                  </button>
                </div>

                {/* In-Text + Annotation */}
                <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 text-xs text-slate-600 dark:text-slate-300">
                  <div className="flex items-center gap-2 flex-wrap">
                    <span className="font-semibold text-slate-500 dark:text-slate-400">In-text:</span>
                    <code className="font-mono text-slate-800 dark:text-slate-200">
                      {entry.inText || `(${entry.authors.split(',')[0] || 'Author'}, ${entry.year || 'n.d.'})`}
                    </code>
                    <button
                      type="button"
                      onClick={() =>
                        void handleCopy(
                          `${entry.id}_intext`,
                          entry.inText || `(${entry.authors.split(',')[0] || 'Author'}, ${entry.year || 'n.d.'})`
                        )
                      }
                      className="text-indigo-600 dark:text-indigo-400 hover:underline"
                    >
                      {isInTextCopied ? 'Copied' : 'Copy'}
                    </button>
                  </div>
                </div>

                {entry.annotation && (
                  <p className="text-xs leading-relaxed text-slate-600 dark:text-slate-300 border-t border-slate-100 dark:border-slate-800 pt-2.5">
                    <span className="font-semibold text-slate-700 dark:text-slate-200">Annotation: </span>
                    {entry.annotation}
                  </p>
                )}
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}
